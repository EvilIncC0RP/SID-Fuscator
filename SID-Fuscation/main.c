int main(void)
{

    PrintBanner();


    SID_OUTPUT_MODE outputMode;

    if (!ReadOutputMode(
        &outputMode
    ))
    {
        return 1;
    }

    BOOL debugEnabled = FALSE;

    if (!ReadDebugMode(
        &debugEnabled
    ))
    {
        return 1;
    }

    printf("\n");

    int exitCode = 1;

    const BYTE* original = g_InputPayload;
    SIZE_T originalSize = g_InputPayloadSize;

    if (original == NULL ||
        originalSize == 0)
    {
        printf(
            "[-] Input payload is empty.\n"
        );

        return 1;
    }

    if (originalSize > (SIZE_T)-1 - (BLOCK_SIZE - 1))
    {
        printf("[-] Input payload is too large.\n");
        return 1;
    }

    SIZE_T remainder = originalSize % BLOCK_SIZE;
    SIZE_T paddingSize = 0;
    SIZE_T paddedSize = originalSize;

    if (remainder != 0)
    {
        paddingSize = BLOCK_SIZE - remainder;
        paddedSize = originalSize + paddingSize;
    }

    if (debugEnabled)
    {
        printf(
            "[i] Original size: %zu bytes\n",
            originalSize
        );

        printf(
            "[i] Padding size:  %zu bytes\n",
            paddingSize
        );

        printf(
            "[i] Padded size:   %zu bytes\n\n",
            paddedSize
        );
    }

    HANDLE processHeap = GetProcessHeap();
    SIZE_T blockCount =
        paddedSize / BLOCK_SIZE;

    SIZE_T sidCount =
        (blockCount + MAX_DWORDS_PER_SID - 1)
        / MAX_DWORDS_PER_SID;

    if (sidCount >
        (SIZE_T)-1 /
        (SID_STRING_CAPACITY * sizeof(WCHAR)))
    {
        printf("[-] SID storage size overflow.\n");
        return 1;
    }

    if (debugEnabled)
    {
        printf(
            "[i] Block count: %zu\n",
            blockCount
        );

        printf(
            "[i] SID count:   %zu\n",
            sidCount
        );
    }

    if (processHeap == NULL)
    {
        printf("[-] GetProcessHeap failed: %lu\n", GetLastError());
        return 1;
    }

    BYTE* padded = HeapAlloc(
        processHeap,
        HEAP_ZERO_MEMORY,
        paddedSize
    );

    BYTE* permuted = HeapAlloc(
        processHeap,
        HEAP_ZERO_MEMORY,
        paddedSize
    );


    DWORD* packed = HeapAlloc(
        processHeap,
        HEAP_ZERO_MEMORY,
        blockCount * sizeof(DWORD)
    );


    WCHAR* sidStringsStorage = HeapAlloc(
        processHeap,
        HEAP_ZERO_MEMORY,
        sidCount * SID_STRING_CAPACITY * sizeof(WCHAR)
    );

    PCWSTR* sidPayload = HeapAlloc(
        processHeap,
        HEAP_ZERO_MEMORY,
        sidCount * sizeof(PCWSTR)
    );


    if (padded == NULL ||
        permuted == NULL ||
        packed == NULL ||
        sidStringsStorage == NULL ||
        sidPayload == NULL
        )
    {
        printf("[-] HeapAlloc failed. \n");

        if (padded != NULL)
            HeapFree(processHeap, 0, padded);
        if (permuted != NULL)
            HeapFree(processHeap, 0, permuted);
        if (packed != NULL)
            HeapFree(processHeap, 0, packed);
        if (sidStringsStorage != NULL)
            HeapFree(processHeap, 0, sidStringsStorage);
        if (sidPayload != NULL)
            HeapFree(processHeap, 0, sidPayload);

        return 1;
    }

    memcpy(
        padded,
        original,
        originalSize
    );



    for (SIZE_T blockIndex = 0;
        blockIndex < blockCount;
        blockIndex++)
    {
        SIZE_T offset =
            blockIndex * BLOCK_SIZE;

        PermuteBlock(
            padded + offset,
            permuted + offset,
            blockIndex
        );
    }

    PackBlocksToDwords(
        permuted,
        packed,
        blockCount
    );

    if (debugEnabled)
    {
        printf("\n[DEBUG] Original: ");
        PrintBuffer(
            original,
            originalSize
        );

        printf("[DEBUG] Padded:   ");
        PrintBuffer(
            padded,
            paddedSize
        );

        printf("[DEBUG] Permuted: ");
        PrintBuffer(
            permuted,
            paddedSize
        );

        printf("[DEBUG] Packed:   ");
        PrintDwords(
            packed,
            blockCount
        );

        printf("\n");
    }

    for (SIZE_T sidIndex = 0;
        sidIndex < sidCount;
        sidIndex++)
    {

        SIZE_T dwordOffset =
            sidIndex * MAX_DWORDS_PER_SID;

        SIZE_T remainingDwords =
            blockCount - dwordOffset;

        SIZE_T dwordsInCurrentSid =
            remainingDwords > MAX_DWORDS_PER_SID
            ? MAX_DWORDS_PER_SID
            : remainingDwords;

        PWSTR currentSidString =
            sidStringsStorage +
            (sidIndex * SID_STRING_CAPACITY);

        sidPayload[sidIndex] = currentSidString;


        if (!BuildSidString(
            packed + dwordOffset,
            dwordsInCurrentSid,
            currentSidString,
            SID_STRING_CAPACITY
        ))
        {
            printf(
                "[-] BuildSidString failed for SID [%zu]. \n",
                sidIndex
            );
            goto CleanupMain;
        }

        if (debugEnabled)
        {
            printf(
                "[DEBUG] SID[%zu]: %ls\n",
                sidIndex,
                currentSidString
            );
        }


}


    if (outputMode == SID_OUTPUT_CONSOLE ||
        outputMode == SID_OUTPUT_BOTH)
    {
        PrintSidPayloadAsCCode(
            sidPayload,
            sidCount,
            originalSize
        );
    }

    if (outputMode == SID_OUTPUT_FILE ||
        outputMode == SID_OUTPUT_BOTH)
    {
        if (!WriteSidPayloadHeader(
            sidPayload,
            sidCount,
            originalSize,
            "generated_payload.h"
        ))
        {
            printf(
                "[-] WriteSidPayloadHeader failed.\n"
            );

            goto CleanupMain;
        }

        printf(
            "[+] generated_payload.h created successfully.\n"
        );
    }


    printf(
        "\n[+] SID payload generated successfully.\n"
    );

    exitCode = 0;

CleanupMain:

    HeapFree(processHeap, 0, padded);
    HeapFree(processHeap, 0, permuted);
    HeapFree(processHeap, 0, packed);
    HeapFree(processHeap, 0, sidStringsStorage);
    HeapFree(processHeap, 0, sidPayload);

    return exitCode;
}
