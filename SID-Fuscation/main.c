static BOOL ReadOutputMode(
    SID_OUTPUT_MODE* outputMode
)
{
    if (outputMode == NULL)
    {
        return FALSE;
    }

    *outputMode = 0;

    char input[32] = { 0 };

    for (;;)
    {
        printf(
            "Select output mode:\n"
            "[1] Print SID payload to console\n"
            "[2] Write generated_payload.h\n"
            "[3] Print and write file\n"
            "\n"
            "Selection: "
        );

        if (fgets(
            input,
            sizeof(input),
            stdin
        ) == NULL)
        {
            printf(
                "\n[-] Failed to read input.\n"
            );

            return FALSE;
        }

        if (strchr(input, '\n') == NULL)
        {
            int character = 0;

            while ((character = getchar()) != '\n' &&
                character != EOF)
            {
                /* Clear remaining input. */
            }

            printf(
                "[-] Input is too long. "
                "Enter 1, 2 or 3.\n\n"
            );

            continue;
        }

        errno = 0;

        char* endPointer = NULL;

        long selectedMode = strtol(
            input,
            &endPointer,
            10
        );

        if (endPointer == input)
        {
            printf(
                "[-] Input must be a number: "
                "1, 2 or 3.\n\n"
            );

            continue;
        }

        while (*endPointer != '\0' &&
            isspace((unsigned char)*endPointer))
        {
            endPointer++;
        }

        if (errno != 0 ||
            *endPointer != '\0' ||
            selectedMode < SID_OUTPUT_CONSOLE ||
            selectedMode > SID_OUTPUT_BOTH)
        {
            printf(
                "[-] Invalid selection. "
                "Enter 1, 2 or 3.\n\n"
            );

            continue;
        }

        *outputMode =
            (SID_OUTPUT_MODE)selectedMode;

        return TRUE;
    }
}

